#!/usr/bin/env node
/**
 * Regenerates src/data/mock/districts.ts from public/geo/tn-districts.geojson.
 *
 * For each of the 38 districts it finds the "pole of inaccessibility" — the interior point furthest
 * from the district boundary — by grid search, then records:
 *   lat/lng  the point itself (always well inside the district, never offshore)
 *   jitter   a safe scatter radius in degrees (60% of the clearance to the boundary, capped)
 *
 * generateMockData scatters that district's quarries within ±jitter, which is what keeps every
 * quarry inside the district it is labelled with while still spreading them far enough apart to
 * render as separate markers.
 *
 * Run with: node scripts/build-district-centers.mjs   (after build-district-geojson.mjs)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as turf from "@turf/turf";

const GEOJSON_PATH = fileURLToPath(new URL("../public/geo/tn-districts.geojson", import.meta.url));
const OUT_PATH = fileURLToPath(new URL("../src/data/mock/districts.ts", import.meta.url));

const KM_PER_DEG = 111;
const COARSE_STEPS = 26;
const FINE_STEPS = 12;
const JITTER_FACTOR = 0.6;
const JITTER_MIN = 0.02;
const JITTER_MAX = 0.08;

function boundaryLines(feature) {
  const asLines = turf.polygonToLine(feature);
  const features = asLines.type === "FeatureCollection" ? asLines.features : [asLines];
  return features.flatMap((f) =>
    f.geometry.type === "MultiLineString"
      ? f.geometry.coordinates.map((c) => turf.lineString(c))
      : [f]
  );
}

/** Distance from a point to the district edge, in degrees. */
function clearance(lines, lng, lat) {
  const pt = turf.point([lng, lat]);
  let min = Infinity;
  for (const line of lines) {
    min = Math.min(min, turf.pointToLineDistance(pt, line, { units: "kilometers" }));
  }
  return min / KM_PER_DEG;
}

function search(feature, lines, [minX, minY, maxX, maxY], steps, best) {
  for (let i = 0; i <= steps; i++) {
    for (let j = 0; j <= steps; j++) {
      const lng = minX + ((maxX - minX) * i) / steps;
      const lat = minY + ((maxY - minY) * j) / steps;
      if (!turf.booleanPointInPolygon(turf.point([lng, lat]), feature)) continue;
      const c = clearance(lines, lng, lat);
      if (c > best.clearance) best = { lng, lat, clearance: c };
    }
  }
  return best;
}

const geo = JSON.parse(readFileSync(GEOJSON_PATH, "utf8"));
const rows = [];

for (const feature of geo.features) {
  const name = feature.properties.district;
  const lines = boundaryLines(feature);
  const bbox = turf.bbox(feature);

  // Coarse pass over the bounding box, then a finer pass around the best candidate.
  let best = search(feature, lines, bbox, COARSE_STEPS, { lng: 0, lat: 0, clearance: -1 });
  const span = Math.max((bbox[2] - bbox[0]) / COARSE_STEPS, (bbox[3] - bbox[1]) / COARSE_STEPS);
  best = search(
    feature,
    lines,
    [best.lng - span, best.lat - span, best.lng + span, best.lat + span],
    FINE_STEPS,
    best
  );

  const jitter = Math.max(JITTER_MIN, Math.min(JITTER_MAX, best.clearance * JITTER_FACTOR));
  rows.push({
    name,
    lat: Math.round(best.lat * 1000) / 1000,
    lng: Math.round(best.lng * 1000) / 1000,
    jitter: Math.round(jitter * 1000) / 1000,
  });
}

rows.sort((a, b) => a.name.localeCompare(b.name));

const key = (n) => (/^[A-Za-z][A-Za-z0-9]*$/.test(n) ? n : JSON.stringify(n));
const body = rows
  .map((r) => `  ${key(r.name)}: { lat: ${r.lat}, lng: ${r.lng}, jitter: ${r.jitter} },`)
  .join("\n");

writeFileSync(
  OUT_PATH,
  `import type { District } from "../../types/common";

/**
 * GENERATED by scripts/build-district-centers.mjs — edit that script, not this file.
 *
 * For each of Tamil Nadu's 38 districts: the most-interior point of the district (furthest from its
 * boundary) and \`jitter\`, the safe scatter radius in degrees around it. generateMockData places a
 * district's quarries within ±jitter, which keeps every quarry inside the district it is labelled
 * with while still spreading them far enough apart to read as separate markers on the map.
 */
export const DISTRICT_CENTERS: Record<
  District,
  { lat: number; lng: number; jitter: number }
> = {
${body}
};

/** Tamil Nadu's real bounding box — used to clamp jittered coordinates and frame the map. */
export const TN_BOUNDS = {
  minLat: 8.0,
  maxLat: 13.6,
  minLng: 76.2,
  maxLng: 80.4,
};

export const TN_CENTER = { lat: 10.9, lng: 78.4 };
`
);

console.log(`Wrote ${OUT_PATH} (${rows.length} districts)`);
console.log(
  "tightest jitter:",
  rows
    .slice()
    .sort((a, b) => a.jitter - b.jitter)
    .slice(0, 5)
    .map((r) => `${r.name} ${r.jitter}`)
    .join(", ")
);
